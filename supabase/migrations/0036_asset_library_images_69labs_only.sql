-- Reuse only 69labs stills. Supersedes 0035's fallback deny-list.
--
-- WHY THIS IS TIGHTER THAN 0035
-- -----------------------------
-- 0035 excluded fal_flux_image / gemini_image from the reuse pool. That was not
-- enough, because of a backfill mislabel:
--
--   scripts/asset-library-backfill.ts indexes a segment's still using the
--   SEGMENT's `provider` column. For an ai_clip segment, imageToVideoProcessor
--   writes the IMAGE's provider when the still lands (:118) and then OVERWRITES
--   that column with the CLIP's provider when the animation lands (:158). So the
--   backfill recorded a 69labs still as "ltx2". Same for split_2, whose right
--   half is a 69labs still on a segment whose provider is "heygen".
--
-- Measured 2026-08-15: 723 ltx2 + 249 heygen rows with asset_type='image' —
-- every one a .jpg under /images/. LTX-2 is image-to-video and HeyGen renders
-- avatar video; neither emits a standalone still, which is what proves these are
-- mislabels and not real LTX/HeyGen images.
--
-- The consequence: a still generated by the FLUX fallback during an ai_clip job
-- is now indistinguishable from a 69labs one — both read "ltx2", and the true
-- image provider was overwritten and is unrecoverable. A deny-list cannot
-- separate them. An allow-list can, at the cost of ~972 rows (~2% of the 43.7k
-- clean pool) that are probably fine but cannot be proven so.
--
-- IMAGES ONLY. Clips are untouched: ltx2 is the only clip provider there is, so
-- applying the same allow-list to them would disable clip reuse entirely.
--
-- Live counts when this was written (asset_type='image'):
--   sixtynine_image 43710  <- the only rows this function will now return
--   fal_flux_image  19454  <- removed fallback, off-style
--   ltx2              723  <- mislabelled, true provider unrecoverable
--   gemini_image      311  <- removed fallback, off-style
--   heygen            249  <- mislabelled, true provider unrecoverable

create or replace function public.match_generated_assets(
  query_embedding vector(768),
  match_asset_type text,
  match_is_product boolean,
  min_similarity double precision,
  match_limit integer,
  exclude_urls text[] default '{}'
)
returns table (
  id uuid,
  asset_url text,
  source_image_url text,
  prompt text,
  provider text,
  similarity double precision,
  reuse_count integer,
  last_reused_at timestamptz
)
language sql
stable
as $$
  select
    ga.id,
    ga.asset_url,
    ga.source_image_url,
    ga.prompt,
    ga.provider,
    1 - (ga.prompt_embedding <=> query_embedding) as similarity,
    ga.reuse_count,
    ga.last_reused_at
  from public.generated_assets ga
  where ga.asset_type = match_asset_type
    and ga.is_product = match_is_product
    and ga.prompt_embedding is not null
    and 1 - (ga.prompt_embedding <=> query_embedding) >= min_similarity
    and not (ga.asset_url = any(exclude_urls))
    -- Images: 69labs only. Clips: unrestricted. Applied inside the function,
    -- BEFORE `limit match_limit` — filtering the returned rows app-side would
    -- spend the limit on rows that are then discarded, reporting "no match"
    -- while eligible 69labs rows sat just outside the window.
    and (
      match_asset_type <> 'image'
      or ga.provider = 'sixtynine_image'
    )
  order by ga.prompt_embedding <=> query_embedding
  limit match_limit;
$$;

comment on function public.match_generated_assets is
  'Nearest-neighbour reuse lookup over generated_assets. IMAGE reuse is '
  'restricted to provider = sixtynine_image (2026-08-15): the removed '
  'Gemini/FLUX fallback stills are off-style, and ltx2/heygen-labelled stills '
  'are backfill mislabels whose true provider is unrecoverable. Clip reuse is '
  'unrestricted.';
